<script lang="ts">
	import { enhance } from '$app/forms';
	import DraftRow, { type DraftInit } from './DraftRow.svelte';
	import SettingsEditor from './SettingsEditor.svelte';
	import { OPERAND_LABEL, type OperandKind, type WizardPreview } from '#lib/domain/wizard.ts';

	interface Props {
		/** A new set, or more tasks for an existing set. */
		target: { kind: 'new' } | { kind: 'add'; setId: string; setName: string };
		/** Result of the last form action of the page. */
		form: { preview?: WizardPreview; error?: string; where?: string } | null | undefined;
	}

	let { target, form }: Props = $props();

	const OPS = [
		{ value: '+', symbol: '+', label: 'Plus' },
		{ value: '-', symbol: '−', label: 'Minus' },
		{ value: '+-', symbol: '±', label: 'Plus und Minus' },
		{ value: '*', symbol: '·', label: 'Mal' },
		{ value: ':', symbol: ':', label: 'Geteilt' },
		{ value: '*:', symbol: '·:', label: 'Mal und Geteilt' }
	];
	const RANGES = [6, 10, 20, 100, 1000];

	// answers of step 1
	let op = $state('+');
	let range = $state(20);
	let gaps = $state<string[]>(['result']);
	let tenTransition = $state('any');
	let hundredTransition = $state('any');
	let decompose = $state('none');
	let count = $state(10);
	let rounds = $state(1);
	let rows = $state<string[]>([]);
	// fine settings
	let firstKind = $state<OperandKind>('any');
	let secondKind = $state<OperandKind>('any');
	let factorFrom = $state(1);
	let factorTo = $state(10);

	const addSub = $derived(op === '+' || op === '-' || op === '+-');
	const operandKinds = $derived(
		(Object.keys(OPERAND_LABEL) as OperandKind[]).filter((k) => {
			if (k === 'any' || k === 'ones' || k === 'fixed') return true;
			if (k === 'hundreds' || k === 'threeDigit') return range === 1000;
			return range >= 100;
		})
	);
	// a choice that does not fit the number range any more goes back to "any"
	$effect(() => {
		if (!operandKinds.includes(firstKind)) firstKind = 'any';
		if (!operandKinds.includes(secondKind)) secondKind = 'any';
	});

	// ----- drafts: generated by the wizard or typed in by hand -----
	let mode = $state<'generate' | 'manual'>('generate');
	let preview = $state<WizardPreview | null>(null);
	let previewId = $state(0);
	let items = $state<{ id: number; draft: DraftInit }[]>([]);
	let nextId = $state(0);
	let rowStates = $state<Record<number, { include: boolean; problem: boolean }>>({});
	let name = $state('');
	let nameTouched = false;
	let lastForm: unknown = null;

	$effect(() => {
		const f = form;
		if (f && f !== lastForm && f.preview) {
			lastForm = f;
			const p = f.preview;
			preview = p;
			previewId += 1;
			mode = 'generate';
			items = p.drafts.map((d, i) => ({
				id: i,
				draft: { expr: d.expr, answer: d.answer, hint: d.hint, decompose: d.decompose }
			}));
			nextId = items.length;
			rowStates = {};
			if (!nameTouched) name = p.name;
		}
	});

	function startManual() {
		mode = 'manual';
		preview = null;
		previewId += 1;
		rowStates = {};
		items = [];
		nextId = 0;
		addRows(3);
	}

	function backToWizard() {
		mode = 'generate';
		preview = null;
		items = [];
		rowStates = {};
		nextId = 0;
	}

	function addRows(n: number) {
		const more = Array.from({ length: n }, (_, i) => ({
			id: nextId + i,
			draft: { answer: null } as DraftInit
		}));
		nextId += n;
		items = [...items, ...more];
	}

	function remove(id: number) {
		items = items.filter((it) => it.id !== id);
		delete rowStates[id];
	}

	function setState(i: number, st: { include: boolean; problem: boolean }) {
		const old = rowStates[i];
		if (!old || old.include !== st.include || old.problem !== st.problem) rowStates[i] = st;
	}

	const included = $derived(Object.values(rowStates).filter((s) => s.include).length);
	const problemCount = $derived(
		Object.values(rowStates).filter((s) => s.include && s.problem).length
	);
	const keep =
		() =>
		async ({ update }: { update: (o?: { reset?: boolean }) => Promise<void> }) =>
			update({ reset: false });
</script>

<div class="wizard stack">
	{#if mode === 'generate'}
		<form method="POST" action="?/preview" use:enhance={keep} class="card stack">
			<h2>1. Was soll geübt werden?</h2>

			<fieldset class="tiles">
				<legend>Rechenart</legend>
				{#each OPS as o (o.value)}
					<label class="tile" class:sel={op === o.value}>
						<input
							type="radio"
							name="p.op"
							value={o.value}
							bind:group={op}
							class="visually-hidden"
						/>
						<span class="sym" class:dot={o.symbol.startsWith('·')} aria-hidden="true"
							>{o.symbol}</span
						>
						<span>{o.label}</span>
					</label>
				{/each}
			</fieldset>

			{#if addSub}
				<fieldset class="tiles">
					<legend>Zahlenraum</legend>
					{#each RANGES as r (r)}
						<label class="tile" class:sel={range === r}>
							<input
								type="radio"
								name="p.range"
								value={r}
								bind:group={range}
								class="visually-hidden"
							/>
							<span class="sym">{r}</span>
							<span>bis {r}</span>
						</label>
					{/each}
				</fieldset>
			{:else}
				<fieldset>
					<legend>Welche Reihen?</legend>
					<div class="row">
						{#each Array.from({ length: 10 }, (_, i) => String(i + 1)) as r (r)}
							<label class="row check">
								<input type="checkbox" name="p.rows" value={r} bind:group={rows} />
								{r}er
							</label>
						{/each}
					</div>
					<p class="muted small">Nichts angehakt: alle Reihen von 1 bis 10.</p>
				</fieldset>
			{/if}

			<fieldset>
				<legend>Was ist gesucht?</legend>
				<div class="row">
					<label class="row check"
						><input type="checkbox" name="p.gaps" value="result" bind:group={gaps} /> das Ergebnis</label
					>
					<label class="row check"
						><input type="checkbox" name="p.gaps" value="a" bind:group={gaps} /> die 1. Zahl</label
					>
					<label class="row check"
						><input type="checkbox" name="p.gaps" value="b" bind:group={gaps} /> die 2. Zahl</label
					>
				</div>
				{#if gaps.length === 0}
					<p class="muted small">Nichts angehakt: Es wird das Ergebnis gesucht.</p>
				{/if}
			</fieldset>

			{#if addSub && range >= 20}
				<fieldset>
					<legend>Zehnerübergang</legend>
					<div class="row">
						<label class="row check"
							><input type="radio" name="p.tenTransition" value="any" bind:group={tenTransition} /> egal</label
						>
						<label class="row check"
							><input
								type="radio"
								name="p.tenTransition"
								value="without"
								bind:group={tenTransition}
							/> ohne Übergang</label
						>
						<label class="row check"
							><input type="radio" name="p.tenTransition" value="with" bind:group={tenTransition} /> mit
							Übergang</label
						>
					</div>
				</fieldset>
			{/if}

			{#if addSub && range === 1000}
				<fieldset>
					<legend>Hunderterübergang</legend>
					<div class="row">
						<label class="row check"
							><input
								type="radio"
								name="p.hundredTransition"
								value="any"
								bind:group={hundredTransition}
							/> egal</label
						>
						<label class="row check"
							><input
								type="radio"
								name="p.hundredTransition"
								value="without"
								bind:group={hundredTransition}
							/> ohne Übergang</label
						>
						<label class="row check"
							><input
								type="radio"
								name="p.hundredTransition"
								value="with"
								bind:group={hundredTransition}
							/> mit Übergang</label
						>
					</div>
				</fieldset>
			{/if}

			{#if addSub}
				<fieldset>
					<legend>Zahlzerlegung</legend>
					<div class="row">
						<label class="row check"
							><input type="radio" name="p.decompose" value="none" bind:group={decompose} /> keine</label
						>
						<label class="row check"
							><input type="radio" name="p.decompose" value="show" bind:group={decompose} /> anzeigen</label
						>
						<label class="row check"
							><input type="radio" name="p.decompose" value="fill" bind:group={decompose} /> vom Kind
							ausfüllen lassen</label
						>
					</div>
					<p class="muted small">
						Beispiel: <span class="a">8</span> + <span class="b">7</span> = <span class="a">8</span>
						+ <span class="b">2</span> + <span class="b">5</span> = 15. Die Zerlegung gibt es bei Aufgaben
						mit gesuchtem Ergebnis, wenn sie sinnvoll ist (Übergang zur nächsten Zehnerzahl oder Zehner
						und Einer).
					</p>
				</fieldset>
			{/if}

			<div class="grid-2">
				<label class="field">
					<span>Anzahl der Aufgaben</span>
					<input name="p.count" type="number" min="1" max="100" bind:value={count} required />
				</label>
				{#if target.kind === 'new'}
					<fieldset>
						<legend>Wie oft alle Aufgaben?</legend>
						<div class="row">
							{#each [1, 2, 3] as r (r)}
								<label class="row check"
									><input type="radio" name="p.rounds" value={r} bind:group={rounds} />
									{r}×</label
								>
							{/each}
						</div>
					</fieldset>
				{/if}
			</div>
			{#if target.kind === 'new'}
				<p class="muted">
					Das Rennen hat dann <strong>{(Number(count) || 0) * rounds} Aufgaben</strong>.
				</p>
			{/if}

			<details class="fine">
				<summary
					><strong>Feineinstellung</strong> <span class="muted small">(optional)</span></summary
				>
				<div class="stack fine-body">
					{#if addSub}
						<div class="grid-2">
							<div class="stack">
								<label class="field">
									<span>1. Zahl</span>
									<select name="p.first.kind" bind:value={firstKind}>
										{#each operandKinds as k (k)}
											<option value={k}>{OPERAND_LABEL[k]}</option>
										{/each}
									</select>
								</label>
								{#if firstKind === 'fixed'}
									<label class="field">
										<span>Welche Zahlen? (z. B. 6, 7)</span>
										<input name="p.first.fixed" maxlength="200" />
									</label>
								{/if}
							</div>
							<div class="stack">
								<label class="field">
									<span>2. Zahl</span>
									<select name="p.second.kind" bind:value={secondKind}>
										{#each operandKinds as k (k)}
											<option value={k}>{OPERAND_LABEL[k]}</option>
										{/each}
									</select>
								</label>
								{#if secondKind === 'fixed'}
									<label class="field">
										<span>Welche Zahlen? (z. B. 6, 7)</span>
										<input name="p.second.fixed" maxlength="200" />
									</label>
								{/if}
							</div>
						</div>
						<label class="row check"
							><input type="checkbox" name="p.allowZero" /> Auch die Null als Zahl oder Ergebnis erlauben</label
						>
					{:else}
						<div class="grid-2">
							<label class="field">
								<span>Faktor von</span>
								<input name="p.factorFrom" type="number" min="0" max="20" bind:value={factorFrom} />
							</label>
							<label class="field">
								<span>Faktor bis</span>
								<input name="p.factorTo" type="number" min="0" max="20" bind:value={factorTo} />
							</label>
						</div>
						{#if op !== ':'}
							<label class="field">
								<span>Schreibweise</span>
								<select name="p.orientation">
									<option value="kxn">3 · 5 (Reihe hinten)</option>
									<option value="nxk">5 · 3 (Reihe vorne)</option>
									<option value="both">beides (Tauschaufgaben)</option>
								</select>
							</label>
						{/if}
					{/if}
					<p>
						<button type="button" class="linklike" onclick={startManual}
							>Stattdessen Aufgaben selbst festlegen …</button
						>
					</p>
				</div>
			</details>

			{#if form?.error && form.where === 'preview'}<p class="error" role="alert">
					{form.error}
				</p>{/if}
			<div class="row">
				<button class="btn btn-primary big">{preview ? 'Neu erzeugen' : 'Aufgaben erzeugen'}</button
				>
				<button type="button" class="btn" onclick={startManual}>Aufgaben selbst festlegen</button>
			</div>
		</form>
	{:else}
		<div class="card stack">
			<h2>Aufgaben selbst festlegen</h2>
			<p class="muted">
				Trage die Aufgaben ein. Wenn du mehr brauchst, füge mit „+ Aufgabe“ weitere Zeilen hinzu.
				Leere Zeilen werden ignoriert. Das Ergebnis wird automatisch ausgerechnet.
			</p>
			<p>
				<button type="button" class="linklike" onclick={backToWizard}
					>← Zurück zum Assistenten</button
				>
			</p>
		</div>
	{/if}

	{#if items.length > 0}
		<form method="POST" action="?/save" use:enhance={keep} class="card stack preview">
			<h2>{mode === 'manual' ? '2. Aufgaben' : '2. Vorschau'} ({included} Aufgaben)</h2>
			<input type="hidden" name="count" value={nextId} />
			<input
				type="hidden"
				name="origin"
				value={JSON.stringify(preview?.origin ?? { kind: 'manual' })}
			/>
			<input type="hidden" name="tags" value={(preview?.tags ?? []).join(', ')} />
			{#if mode === 'generate'}<input type="hidden" name="rounds" value={rounds} />{/if}

			{#if preview?.warnings.length}
				<div class="notice" role="status">
					{#each preview.warnings as w (w)}<p>{w}</p>{/each}
				</div>
			{/if}

			<div class="table-wrap">
				<table>
					<thead>
						<tr>
							<th>Nehmen</th><th>Zahl 1</th><th></th><th>Zahl 2</th><th>Gesucht</th><th>Antwort</th
							><th>Zerlegung</th><th>Eigene Hilfe</th>{#if mode === 'manual'}<th></th>{/if}
						</tr>
					</thead>
					<tbody>
						{#each items as it (previewId + '-' + it.id)}
							<DraftRow
								index={it.id}
								draft={it.draft}
								onstate={setState}
								onremove={mode === 'manual' ? () => remove(it.id) : undefined}
							/>
						{/each}
					</tbody>
				</table>
			</div>
			{#if mode === 'manual'}
				<div class="row">
					<button type="button" class="btn" onclick={() => addRows(1)}>+ Aufgabe</button>
					<button type="button" class="btn" onclick={() => addRows(5)}>+ 5 Aufgaben</button>
				</div>
			{/if}

			{#if target.kind === 'new'}
				<div class="grid-2">
					<label class="field">
						<span>Name des Sets *</span>
						<input
							name="name"
							required
							maxlength="120"
							bind:value={name}
							oninput={() => (nameTouched = true)}
						/>
					</label>
					<label class="field">
						<span>Beschreibung (für das Kind sichtbar)</span>
						<input name="description" maxlength="1000" />
					</label>
				</div>
				{#if mode === 'manual'}
					<fieldset>
						<legend>Wie oft alle Aufgaben?</legend>
						<div class="row">
							{#each [1, 2, 3] as r (r)}
								<label class="row check"
									><input type="radio" name="rounds" value={r} bind:group={rounds} /> {r}×</label
								>
							{/each}
						</div>
						<p class="muted small">
							Das Rennen hat dann <strong>{included * rounds} Aufgaben</strong>.
						</p>
					</fieldset>
				{/if}
				<SettingsEditor
					level="set"
					layer={{}}
					exclude={['rounds']}
					title="Einstellungen für dieses Set"
				/>
			{/if}

			{#if problemCount > 0}
				<p class="calc-summary" role="status">
					Bei {problemCount} Aufgabe(n) geht die Rechnung nicht auf. Bitte oben korrigieren oder die Aufgabe
					abwählen.
				</p>
			{/if}
			{#if form?.error && form.where !== 'preview'}<p class="error" role="alert">
					{form.error}
				</p>{/if}
			<div>
				<button class="btn btn-primary big" disabled={included === 0}>
					{target.kind === 'new' ? 'Set speichern' : `Zum Set „${target.setName}“ hinzufügen`}
				</button>
			</div>
		</form>
	{/if}
</div>

